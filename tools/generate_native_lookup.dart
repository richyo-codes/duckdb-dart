// Generate address-only native declarations for the existing dynamic bindings.
// Run: dart tools/generate_native_lookup.dart
import 'dart:io';

void main() {
  final bindings = File('lib/src/ffi/duckdb.g.dart').readAsStringSync();
  final symbols =
      RegExp(r"'(?<symbol>duckdb_[a-z0-9_]+)'\);")
          .allMatches(bindings)
          .map((match) => match.namedGroup('symbol')!)
          .toSet()
          .toList()
        ..sort();
  if (symbols.length != RegExp('_lookup<').allMatches(bindings).length) {
    throw StateError(
      'Not every dynamic symbol lookup was recognized. Update the generator.',
    );
  }
  final out = StringBuffer(
    '''// Generated by tools/generate_native_lookup.dart. Do not edit.
// These declarations are used only with Native.addressOf, never called.
// duckdb.g.dart supplies the actual ABI signatures when casting the addresses.
import 'dart:ffi';

Pointer<T> lookupNativeAsset<T extends NativeType>(String symbol) {
  return switch (symbol) {
''',
  );
  for (final symbol in symbols) {
    out.writeln(
      "    '$symbol' => Native.addressOf<NativeFunction<Void Function()>>(_$symbol).cast<T>(),",
    );
  }
  out.writeln(
    "    _ => throw ArgumentError.value(symbol, 'symbol', 'Unknown DuckDB symbol'),\n  };\n}",
  );
  for (final symbol in symbols) {
    out.writeln(
      "\n@Native<Void Function()>(assetId: 'package:dart_duckdb/duckdb', symbol: '$symbol')\nexternal void _$symbol();",
    );
  }
  const destination = 'lib/src/ffi/native_lookup.g.dart';
  File(destination).writeAsStringSync(out.toString());
  final result = Process.runSync(Platform.resolvedExecutable, [
    'format',
    destination,
  ]);
  if (result.exitCode != 0) throw StateError('${result.stderr}');
}
