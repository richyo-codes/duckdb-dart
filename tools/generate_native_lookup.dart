// Generate typed @Native adapters from the ffigen dynamic bindings.
// Run: dart tools/generate_native_lookup.dart
// Keep each declaration's real C signature. The previous addressOf adapter used
// placeholder Void Function() declarations and lost the asset ID in Windows AOT
// on Dart 3.13.6 (CI run 39639605858). Direct typed calls avoid that lookup path;
// the standalone CLI smoke check exercises asset resolution in AOT builds.
import 'dart:io';

void main() {
  final source = File('lib/src/ffi/duckdb.g.dart').readAsStringSync();
  final nativeTypes = <String, String>{};
  for (final match in RegExp(
    r"_lookup<\s*ffi\s*\.NativeFunction<([\s\S]*?)>>\(\s*'(duckdb_[a-z0-9_]+)'\);",
  ).allMatches(source)) {
    nativeTypes[match[2]!] = match[1]!.trim();
  }
  final methods = RegExp(
    r'^  ([\w<>,.?\s]+?) (duckdb_\w+)\(([\s\S]*?)\) \{\n([\s\S]*?)\n  \}',
    multiLine: true,
  ).allMatches(source).toList();
  final count = RegExp('_lookup<').allMatches(source).length;
  if (methods.length != count || nativeTypes.length != count) {
    throw StateError(
      'Not every dynamic binding was recognized. Update the generator.',
    );
  }
  final declarations = StringBuffer();
  final output = StringBuffer(
    '''// Generated by tools/generate_native_lookup.dart. Do not edit.
// Call typed @Native declarations directly; do not route through addressOf.
import 'dart:ffi' as ffi;
import 'package:dart_duckdb/src/ffi/duckdb.g.dart';

class NativeAssetBindings extends Bindings {
  NativeAssetBindings() : super.fromLookup(_unusedLookup);

  static ffi.Pointer<T> _unusedLookup<T extends ffi.NativeType>(String symbol) =>
      throw StateError('Missing native binding for \$symbol');
''',
  );
  for (final method in methods) {
    final symbol = method[2]!;
    final dartType = RegExp(
      '_${symbol}Ptr\\s*\\.asFunction<([\\s\\S]*?)>\\(\\);',
    ).firstMatch(source)?.group(1)?.trim();
    final nativeType = nativeTypes[symbol];
    if (dartType == null || nativeType == null) {
      throw StateError('Missing signature for $symbol');
    }
    final function = dartType.indexOf(' Function(');
    final returnType = dartType.substring(0, function);
    final parameters = splitTypes(
      dartType.substring(function + 10, dartType.length - 1),
    );
    final arguments = [
      for (var i = 0; i < parameters.length; i++) '${parameters[i]} arg$i',
    ].join(', ');
    declarations.writeln(
      "@ffi.Native<$nativeType>(assetId: 'package:dart_duckdb/duckdb', symbol: '$symbol')\nexternal $returnType _native_$symbol($arguments);\n",
    );
    final body = method[4]!.replaceAll('_$symbol(', '_native_$symbol(');
    output.writeln(
      '  @override\n  ${method[1]!.trim()} $symbol(${method[3]}) {\n$body\n  }\n',
    );
  }
  output.writeln('}\n');
  output.write(declarations);
  const destination = 'lib/src/ffi/native_lookup.g.dart';
  File(destination).writeAsStringSync(output.toString());
  final result = Process.runSync(Platform.resolvedExecutable, [
    'format',
    destination,
  ]);
  if (result.exitCode != 0) throw StateError('${result.stderr}');
}

List<String> splitTypes(String input) {
  if (input.trim().isEmpty) return [];
  final result = <String>[];
  var depth = 0;
  var start = 0;
  for (var i = 0; i < input.length; i++) {
    final char = input[i];
    if (char == '<' || char == '(') depth++;
    if (char == '>' || char == ')') depth--;
    if (char == ',' && depth == 0) {
      result.add(input.substring(start, i).trim());
      start = i + 1;
    }
  }
  result.add(input.substring(start).trim());
  return result;
}
